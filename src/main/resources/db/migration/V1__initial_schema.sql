-- Initial relational schema: 20 root entities + 5 joined subtype tables.
-- PostgreSQL 17 and H2 PostgreSQL mode use this same migration.
-- Date ranges are inclusive; leave timestamps describe [start, end).
-- No statutory leave quantities are hard-coded or seeded here.
-- Foreign keys intentionally retain the default NO ACTION delete behavior.
--
-- Application transaction requirements that are not single-row SQL checks:
-- 1. Employee and evaluation subtype rows must match their discriminator and
--    form an exhaustive, exclusive classification. Create parent + subtype
--    atomically; a PK/FK alone does not enforce subtype completeness.
-- 2. Customer evaluators must belong to the project's client. The requesting
--    PM and PM evaluator must be eligible PM participants of that same project.
--    Peer evaluators must be in the same project and cannot evaluate themselves.
-- 3. Assignment dates must fit the project's dates. Prevent unintended duplicate
--    or overlapping role periods and complete evaluations only after project end.
-- 4. Completed evaluations require all mandatory evaluation-item details.
--    The score scale must be agreed before imposing a project-specific upper bound.
-- 5. Leave-policy validity periods for a type must not overlap. The application
--    converts DAY/HOUR policy quantities to minutes using the documented schedule.
-- 6. Annual usage requires approved annual leave, the same employee on request
--    and grant, an unexpired grant and sufficient balance. Approval and deduction
--    must lock the relevant grants and commit atomically. Cancellation preserves
--    usage rows and restores balance by excluding canceled usage.
-- 7. Employee-number generation and authorization are server responsibilities.

CREATE TABLE employee (
    employee_id VARCHAR(20) NOT NULL,
    employee_name VARCHAR(50) NOT NULL,
    resident_no VARCHAR(256) NOT NULL,
    education VARCHAR(30) NOT NULL,
    hired_on DATE NOT NULL,
    login_id VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    employee_type VARCHAR(10) NOT NULL,
    CONSTRAINT pk_employee PRIMARY KEY (employee_id),
    CONSTRAINT uk_employee_login_id UNIQUE (login_id),
    CONSTRAINT ck_employee_type CHECK (employee_type IN ('DEV', 'NONDEV'))
);

CREATE TABLE developer (
    employee_id VARCHAR(20) NOT NULL,
    tech_grade VARCHAR(20) NOT NULL,
    CONSTRAINT pk_developer PRIMARY KEY (employee_id),
    CONSTRAINT fk_developer_employee FOREIGN KEY (employee_id)
        REFERENCES employee (employee_id)
);

CREATE TABLE non_developer (
    employee_id VARCHAR(20) NOT NULL,
    department_name VARCHAR(50) NOT NULL,
    CONSTRAINT pk_non_developer PRIMARY KEY (employee_id),
    CONSTRAINT fk_non_developer_employee FOREIGN KEY (employee_id)
        REFERENCES employee (employee_id)
);

CREATE TABLE access_role (
    role_id VARCHAR(20) NOT NULL,
    role_name VARCHAR(50) NOT NULL,
    CONSTRAINT pk_access_role PRIMARY KEY (role_id)
);

CREATE TABLE employee_role (
    emp_role_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    granted_on DATE NOT NULL,
    employee_id VARCHAR(20) NOT NULL,
    role_id VARCHAR(20) NOT NULL,
    CONSTRAINT pk_employee_role PRIMARY KEY (emp_role_id),
    CONSTRAINT uk_employee_role UNIQUE (employee_id, role_id),
    CONSTRAINT fk_employee_role_employee FOREIGN KEY (employee_id)
        REFERENCES employee (employee_id),
    CONSTRAINT fk_employee_role_role FOREIGN KEY (role_id)
        REFERENCES access_role (role_id)
);

CREATE TABLE client (
    client_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    client_name VARCHAR(100) NOT NULL,
    business_no VARCHAR(20) NOT NULL,
    CONSTRAINT pk_client PRIMARY KEY (client_id)
);

CREATE TABLE client_contact (
    contact_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    contact_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    client_id BIGINT NOT NULL,
    CONSTRAINT pk_client_contact PRIMARY KEY (contact_id),
    CONSTRAINT fk_client_contact_client FOREIGN KEY (client_id)
        REFERENCES client (client_id)
);

CREATE TABLE project (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    project_name VARCHAR(100) NOT NULL,
    start_on DATE NOT NULL,
    end_on DATE,
    project_status VARCHAR(20) DEFAULT 'PLANNED' NOT NULL,
    client_id BIGINT NOT NULL,
    CONSTRAINT pk_project PRIMARY KEY (project_id),
    CONSTRAINT fk_project_client FOREIGN KEY (client_id)
        REFERENCES client (client_id),
    CONSTRAINT ck_project_dates CHECK (end_on IS NULL OR end_on >= start_on),
    CONSTRAINT ck_project_status CHECK (
        project_status IN ('PLANNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELED')
    ),
    CONSTRAINT ck_project_completion CHECK (
        project_status <> 'COMPLETED' OR end_on IS NOT NULL
    )
);

CREATE TABLE project_participation (
    participation_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_id VARCHAR(20) NOT NULL,
    project_id BIGINT NOT NULL,
    CONSTRAINT pk_project_participation PRIMARY KEY (participation_id),
    CONSTRAINT uk_project_employee UNIQUE (project_id, employee_id),
    CONSTRAINT fk_participation_developer FOREIGN KEY (employee_id)
        REFERENCES developer (employee_id),
    CONSTRAINT fk_participation_project FOREIGN KEY (project_id)
        REFERENCES project (project_id)
);

CREATE TABLE job_role (
    job_role_id VARCHAR(20) NOT NULL,
    job_role_name VARCHAR(50) NOT NULL,
    CONSTRAINT pk_job_role PRIMARY KEY (job_role_id)
);

CREATE TABLE assignment_history (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    assigned_from DATE NOT NULL,
    assigned_to DATE NOT NULL,
    participation_id BIGINT NOT NULL,
    job_role_id VARCHAR(20) NOT NULL,
    CONSTRAINT pk_assignment_history PRIMARY KEY (assignment_id),
    CONSTRAINT fk_assignment_participation FOREIGN KEY (participation_id)
        REFERENCES project_participation (participation_id),
    CONSTRAINT fk_assignment_job_role FOREIGN KEY (job_role_id)
        REFERENCES job_role (job_role_id),
    CONSTRAINT ck_assignment_dates CHECK (assigned_to >= assigned_from)
);

CREATE TABLE skill (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    skill_name VARCHAR(100) NOT NULL,
    skill_category VARCHAR(50) NOT NULL,
    CONSTRAINT pk_skill PRIMARY KEY (skill_id)
);

CREATE TABLE employee_skill (
    employee_skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    proficiency VARCHAR(20) NOT NULL,
    experienced_from DATE NOT NULL,
    employee_id VARCHAR(20) NOT NULL,
    skill_id BIGINT NOT NULL,
    CONSTRAINT pk_employee_skill PRIMARY KEY (employee_skill_id),
    CONSTRAINT uk_employee_skill UNIQUE (employee_id, skill_id),
    CONSTRAINT fk_employee_skill_developer FOREIGN KEY (employee_id)
        REFERENCES developer (employee_id),
    CONSTRAINT fk_employee_skill_skill FOREIGN KEY (skill_id)
        REFERENCES skill (skill_id)
);

CREATE TABLE external_career (
    career_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    company_name VARCHAR(100) NOT NULL,
    career_description VARCHAR(500) NOT NULL,
    career_from DATE NOT NULL,
    career_to DATE,
    employee_id VARCHAR(20) NOT NULL,
    CONSTRAINT pk_external_career PRIMARY KEY (career_id),
    CONSTRAINT fk_external_career_developer FOREIGN KEY (employee_id)
        REFERENCES developer (employee_id),
    CONSTRAINT ck_external_career_dates CHECK (
        career_to IS NULL OR career_to >= career_from
    )
);

CREATE TABLE project_evaluation (
    evaluation_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    evaluation_type VARCHAR(10) NOT NULL,
    evaluated_on DATE,
    writing_status VARCHAR(20) DEFAULT 'DRAFT' NOT NULL,
    target_participation_id BIGINT NOT NULL,
    CONSTRAINT pk_project_evaluation PRIMARY KEY (evaluation_id),
    CONSTRAINT fk_evaluation_target FOREIGN KEY (target_participation_id)
        REFERENCES project_participation (participation_id),
    CONSTRAINT ck_evaluation_type CHECK (
        evaluation_type IN ('CUSTOMER', 'PM', 'PEER')
    ),
    CONSTRAINT ck_evaluation_status CHECK (
        writing_status IN ('DRAFT', 'COMPLETED')
    ),
    CONSTRAINT ck_evaluation_completion CHECK (
        writing_status <> 'COMPLETED' OR evaluated_on IS NOT NULL
    )
);

CREATE TABLE customer_evaluation (
    evaluation_id BIGINT NOT NULL,
    evaluator_contact_id BIGINT NOT NULL,
    requester_pm_participation_id BIGINT NOT NULL,
    requested_at TIMESTAMP NOT NULL,
    reported_at TIMESTAMP,
    CONSTRAINT pk_customer_evaluation PRIMARY KEY (evaluation_id),
    CONSTRAINT fk_customer_evaluation_parent FOREIGN KEY (evaluation_id)
        REFERENCES project_evaluation (evaluation_id),
    CONSTRAINT fk_customer_evaluator_contact FOREIGN KEY (evaluator_contact_id)
        REFERENCES client_contact (contact_id),
    CONSTRAINT fk_customer_requester_pm FOREIGN KEY (requester_pm_participation_id)
        REFERENCES project_participation (participation_id),
    CONSTRAINT ck_customer_report_dates CHECK (
        reported_at IS NULL OR reported_at >= requested_at
    )
);

CREATE TABLE pm_evaluation (
    evaluation_id BIGINT NOT NULL,
    evaluator_participation_id BIGINT NOT NULL,
    CONSTRAINT pk_pm_evaluation PRIMARY KEY (evaluation_id),
    CONSTRAINT fk_pm_evaluation_parent FOREIGN KEY (evaluation_id)
        REFERENCES project_evaluation (evaluation_id),
    CONSTRAINT fk_pm_evaluator_participation FOREIGN KEY (evaluator_participation_id)
        REFERENCES project_participation (participation_id)
);

CREATE TABLE peer_evaluation (
    evaluation_id BIGINT NOT NULL,
    evaluator_participation_id BIGINT NOT NULL,
    CONSTRAINT pk_peer_evaluation PRIMARY KEY (evaluation_id),
    CONSTRAINT fk_peer_evaluation_parent FOREIGN KEY (evaluation_id)
        REFERENCES project_evaluation (evaluation_id),
    CONSTRAINT fk_peer_evaluator_participation FOREIGN KEY (evaluator_participation_id)
        REFERENCES project_participation (participation_id)
);

CREATE TABLE evaluation_item (
    item_id VARCHAR(20) NOT NULL,
    item_name VARCHAR(100) NOT NULL,
    item_description VARCHAR(500) NOT NULL,
    CONSTRAINT pk_evaluation_item PRIMARY KEY (item_id)
);

CREATE TABLE evaluation_detail (
    evaluation_id BIGINT NOT NULL,
    item_id VARCHAR(20) NOT NULL,
    score DECIMAL(5, 2) NOT NULL,
    evaluation_content VARCHAR(1000) NOT NULL,
    CONSTRAINT pk_evaluation_detail PRIMARY KEY (evaluation_id, item_id),
    CONSTRAINT fk_evaluation_detail_parent FOREIGN KEY (evaluation_id)
        REFERENCES project_evaluation (evaluation_id),
    CONSTRAINT fk_evaluation_detail_item FOREIGN KEY (item_id)
        REFERENCES evaluation_item (item_id),
    CONSTRAINT ck_evaluation_score CHECK (score >= 0)
);

CREATE TABLE leave_type (
    leave_type_id VARCHAR(20) NOT NULL,
    leave_type_name VARCHAR(50) NOT NULL,
    legal_class VARCHAR(10) NOT NULL,
    CONSTRAINT pk_leave_type PRIMARY KEY (leave_type_id),
    CONSTRAINT ck_leave_legal_class CHECK (
        legal_class IN ('STATUTORY', 'CONTRACT')
    )
);

CREATE TABLE leave_policy (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    effective_from DATE NOT NULL,
    effective_to DATE,
    limit_basis VARCHAR(20) NOT NULL,
    limit_quantity DECIMAL(10, 2) NOT NULL,
    limit_unit VARCHAR(10) NOT NULL,
    deduct_annual_yn CHAR(1) NOT NULL,
    counting_rule VARCHAR(20) NOT NULL,
    policy_description VARCHAR(1000) NOT NULL,
    leave_type_id VARCHAR(20) NOT NULL,
    CONSTRAINT pk_leave_policy PRIMARY KEY (policy_id),
    CONSTRAINT fk_leave_policy_type FOREIGN KEY (leave_type_id)
        REFERENCES leave_type (leave_type_id),
    CONSTRAINT ck_leave_policy_dates CHECK (
        effective_to IS NULL OR effective_to >= effective_from
    ),
    CONSTRAINT ck_leave_limit_basis CHECK (
        limit_basis IN ('YEAR', 'MONTH', 'EVENT', 'NONE')
    ),
    CONSTRAINT ck_leave_limit_quantity CHECK (limit_quantity >= 0),
    CONSTRAINT ck_leave_limit_unit CHECK (limit_unit IN ('DAY', 'HOUR', 'MINUTE')),
    CONSTRAINT ck_leave_deduct_annual CHECK (deduct_annual_yn IN ('Y', 'N')),
    CONSTRAINT ck_leave_counting_rule CHECK (counting_rule IN ('WORKDAY', 'CALENDAR'))
);

CREATE TABLE leave_request (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    leave_start_at TIMESTAMP NOT NULL,
    leave_end_at TIMESTAMP NOT NULL,
    requested_minutes INTEGER NOT NULL,
    requested_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    request_status VARCHAR(20) DEFAULT 'PENDING' NOT NULL,
    processed_at TIMESTAMP,
    policy_id BIGINT NOT NULL,
    applicant_id VARCHAR(20) NOT NULL,
    processor_id VARCHAR(20),
    CONSTRAINT pk_leave_request PRIMARY KEY (request_id),
    CONSTRAINT fk_leave_request_policy FOREIGN KEY (policy_id)
        REFERENCES leave_policy (policy_id),
    CONSTRAINT fk_leave_request_applicant FOREIGN KEY (applicant_id)
        REFERENCES employee (employee_id),
    CONSTRAINT fk_leave_request_processor FOREIGN KEY (processor_id)
        REFERENCES employee (employee_id),
    CONSTRAINT ck_leave_request_dates CHECK (leave_end_at > leave_start_at),
    CONSTRAINT ck_leave_requested_minutes CHECK (requested_minutes > 0),
    CONSTRAINT ck_leave_request_status CHECK (
        request_status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELED')
    ),
    CONSTRAINT ck_leave_processing_pair CHECK (
        (processor_id IS NULL AND processed_at IS NULL)
        OR (processor_id IS NOT NULL AND processed_at IS NOT NULL)
    ),
    CONSTRAINT ck_leave_processed_status CHECK (
        request_status NOT IN ('APPROVED', 'REJECTED')
        OR processor_id IS NOT NULL
    ),
    CONSTRAINT ck_leave_pending_status CHECK (
        request_status <> 'PENDING'
        OR (processor_id IS NULL AND processed_at IS NULL)
    ),
    CONSTRAINT ck_leave_processed_dates CHECK (
        processed_at IS NULL OR processed_at >= requested_at
    )
);

CREATE TABLE annual_leave_grant (
    grant_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    granted_on DATE NOT NULL,
    expires_on DATE NOT NULL,
    granted_minutes INTEGER NOT NULL,
    grant_reason VARCHAR(100) NOT NULL,
    employee_id VARCHAR(20) NOT NULL,
    policy_id BIGINT NOT NULL,
    CONSTRAINT pk_annual_leave_grant PRIMARY KEY (grant_id),
    CONSTRAINT fk_annual_grant_employee FOREIGN KEY (employee_id)
        REFERENCES employee (employee_id),
    CONSTRAINT fk_annual_grant_policy FOREIGN KEY (policy_id)
        REFERENCES leave_policy (policy_id),
    CONSTRAINT ck_annual_grant_dates CHECK (expires_on >= granted_on),
    CONSTRAINT ck_annual_granted_minutes CHECK (granted_minutes > 0)
);

CREATE TABLE annual_leave_usage (
    usage_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    used_minutes INTEGER NOT NULL,
    canceled_yn CHAR(1) DEFAULT 'N' NOT NULL,
    canceled_at TIMESTAMP,
    request_id BIGINT NOT NULL,
    grant_id BIGINT NOT NULL,
    CONSTRAINT pk_annual_leave_usage PRIMARY KEY (usage_id),
    CONSTRAINT uk_request_grant UNIQUE (request_id, grant_id),
    CONSTRAINT fk_annual_usage_request FOREIGN KEY (request_id)
        REFERENCES leave_request (request_id),
    CONSTRAINT fk_annual_usage_grant FOREIGN KEY (grant_id)
        REFERENCES annual_leave_grant (grant_id),
    CONSTRAINT ck_annual_used_minutes CHECK (used_minutes > 0),
    CONSTRAINT ck_annual_canceled CHECK (canceled_yn IN ('Y', 'N')),
    CONSTRAINT ck_annual_canceled_at CHECK (
        (canceled_yn = 'N' AND canceled_at IS NULL)
        OR (canceled_yn = 'Y' AND canceled_at IS NOT NULL)
    )
);
